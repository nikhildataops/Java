public class Unary {
    static void main(String[] args) {
        int a=10;
        System.out.println(++a);
        System.out.println(a--);
        System.out.println(a++);
        System.out.println(--a);
        System.out.println(a++);
        System.out.println(--a);
        System.out.println(a++);
        System.out.println(++a);
        System.out.println("final value of a: "+a);
    }
}
